        "3. PRESERVE product continuity across calls via PREVIOUS_PRODUCT, so that a product's "
        "characteristics are never split or mixed across two different product entries just because "
        "a chunk boundary happened to fall in the middle of its spec table.\n\n"

        "## WHAT COUNTS AS A CHARACTERISTIC\n"
        "Any measurable or descriptive attribute of a product mentioned in the text — dimensions, "
        "weight, power, voltage, capacity, material, certifications, connectivity, included "
        "accessories, warranty, and so on. This list is illustrative, not exhaustive: capture "
        "whatever attribute is actually present in the text, regardless of domain (IT equipment, "
