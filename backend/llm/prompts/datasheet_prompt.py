        "\"Type de batterie : Plomb-acide étanche\\nInterface : USB, RS232, SNMP (en option)\\n"
        "Garantie : 2 ans pièces et main d'œuvre\"\n\n"
        "Expected output:\n"
        "produits = [\n"
        "  {{\n"
        "    nom_produit: 'Onduleur UPS-3000',\n"
        "    PREVIOUS_PRODUCT: 'Oui',\n"
