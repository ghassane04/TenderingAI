        "- **NO HALLUCINATION**: never invent a product, a characteristic, or a value not explicitly "
        "present in the text.\n"
        "- **UNITS**: keep units EXACTLY as written in the source (e.g. '10kW', '230V', '2.5mm²'). Do "
